def verify(root: str) -> int:
    print("\n=== 4. Verify ===")
    _load_backend(root)
    problems = 0

    def check(label: str, fn, blocking: bool = True) -> None:
        nonlocal problems
        try:
            fn()
        except Exception as exc:
            print(f"{BAD if blocking else WARN} {label}: {type(exc).__name__}: {str(exc)[:150]}")
            if blocking:
                problems += 1

    try:
        import sqlalchemy as sa
        from crm_db import get_session_factory
        from email_smtp import smtp_configured, smtp_enabled
    except Exception as exc:
        print(f"{BAD} cannot import the backend: {type(exc).__name__}: {exc}")
        return 1

    def _table() -> None:
        nonlocal problems
        with get_session_factory()() as db:
            if db.execute(sa.text("SELECT to_regclass('public.email_outbox')")).scalar():
                counts = db.execute(sa.text(
                    "SELECT status::text, count(*) FROM email_outbox GROUP BY status")).all()
                total = sum(c for _s, c in counts) or 0
                detail = ", ".join(f"{s}={c}" for s, c in counts) or "empty"
                print(f"{OK} email_outbox table exists ({total} rows: {detail})")
            else:
                print(f"{BAD} email_outbox table missing - migration did not run")
                problems += 1

    def _revision() -> None:
        with get_session_factory()() as db:
            rev = db.execute(sa.text("SELECT version_num FROM alembic_version")).scalar()
            print(f"{OK if rev == '0064' else WARN} alembic revision = {rev} (expected 0064)")

    def _router() -> None:
        from routers.crm import _MODULES
        state = "registered" if "email_outbox" in _MODULES else "NOT registered"
        print(f"{OK if 'email_outbox' in _MODULES else BAD} outbox admin router {state}")

    def _notify_wiring() -> None:
        import inspect

        from services import notify
        have = [n for n in ("notify_user", "notify_role", "notify_roles", "notify_employee")
                if hasattr(notify, n)]
        print(f"{OK} notify helpers: {', '.join(have)}")
        emails = "email" in inspect.signature(notify.notify_user).parameters
        print(f"{OK if emails else BAD} notify_user sends email as well as the bell: {emails}")

    def _approvers() -> None:
        with get_session_factory()() as db:
            rows = db.execute(sa.text("""
                SELECT ro.name::text, r.full_name, r.email
                FROM user_roles ur
                JOIN roles ro ON ro.id = ur.role_id
                JOIN registration_data r ON r.id = ur.user_id
                WHERE COALESCE(r.is_active, TRUE)
                ORDER BY ro.name, r.full_name
            """)).all()
            if not rows:
                print(f"{WARN} no active users hold any CRM role - notifications would reach nobody")
                return
            by_role: dict[str, list[str]] = {}
            for role, name, mail in rows:
                by_role.setdefault(role, []).append(f"{name or '(no name)'} <{mail}>")
            print(f"{OK} recipients by role:")
            for role in sorted(by_role):
                print(f"         {role:<12} {len(by_role[role])}")
                for who in by_role[role][:6]:
                    print(f"                      {who}")
                if len(by_role[role]) > 6:
                    print(f"                      ... and {len(by_role[role]) - 6} more")
            approvers = {w for r in ("HR", "Finance", "RMG") for w in by_role.get(r, [])}
            print(f"{OK if approvers else WARN} a timesheet submit would email "
                  f"{len(approvers)} approver(s)")

    def _employees_without_login() -> None:
        with get_session_factory()() as db:
            n = db.execute(sa.text(
                "SELECT count(*) FROM employees WHERE user_id IS NULL AND COALESCE(is_active,TRUE)"
            )).scalar()
            if n:
                print(f"{OK} {n} active employee(s) have no login account")
                print("         They could never see a bell notification. They now get email")
                print("         at employees.email - this is the gap the change closes.")
            else:
                print(f"{INFO} every active employee has a login account")

    def _smtp() -> None:
        nonlocal problems
        print(f"{OK if smtp_enabled() else BAD} SMTP_ENABLED = {os.getenv('SMTP_ENABLED')}")
        if not smtp_enabled():
            problems += 1
        print(f"{OK if smtp_configured() else BAD} SMTP credentials present")
        if not smtp_configured():
            problems += 1
        print(f"         {os.getenv('SMTP_HOST')}:{os.getenv('SMTP_PORT') or '587'} "
              f"as {os.getenv('SMTP_USER')}")

    def _worker_mode() -> None:
        raw = (os.getenv("EMAIL_OUTBOX_WORKER") or "true").strip().lower()
        if raw in {"0", "false", "no", "off"}:
            print(f"{INFO} QUEUE-ONLY MODE - notifications are recorded, nothing is sent")
            print("         Switch on with: python karnex_email_setup.py --live")
        else:
            print(f"{OK} LIVE - the app sends every "
                  f"{os.getenv('EMAIL_OUTBOX_INTERVAL_SEC') or '20'}s once restarted")

    check("email_outbox table", _table)
    check("alembic revision", _revision, blocking=False)
    check("admin router", _router, blocking=False)
    check("notify wiring", _notify_wiring)
    check("recipient roles", _approvers, blocking=False)
    check("employees without login", _employees_without_login, blocking=False)
    check("SMTP", _smtp)
    check("worker mode", _worker_mode, blocking=False)
    return problems


