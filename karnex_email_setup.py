def run_migration(root: str) -> bool:
    print("\n=== 3. Database migration ===")
    proc = subprocess.run([sys.executable, "-m", "alembic", "upgrade", "head"],
                          cwd=os.path.join(root, "backend"), capture_output=True, text=True)
    out = ((proc.stdout or "") + (proc.stderr or "")).strip()
    for line in out.splitlines()[-20:]:
        print("  " + line)
    if proc.returncode == 0:
        print(f"{OK} migration completed")
        return True
    print(f"{BAD} migration failed (exit {proc.returncode})")
    return False


# ------------------------------------------------------------- backend import

def _load_backend(root: str):
    backend = os.path.join(root, "backend")
    if backend not in sys.path:
        sys.path.insert(0, backend)
    os.chdir(backend)
    for line in _read_env(os.path.join(root, ".env")):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())


