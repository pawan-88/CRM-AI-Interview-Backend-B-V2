def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--status", action="store_true", help="report only, change nothing")
    ap.add_argument("--send", metavar="ADDRESS", help="deliver one real test email")
    ap.add_argument("--live", action="store_true", help="turn the background sender on")
    ap.add_argument("--pause", action="store_true", help="queue only, send nothing")
    args = ap.parse_args()

    print("Karnex email notifications - setup\n")
    root = repo_root()
    print(f"Repo:   {root}")
    print(f"Python: {sys.executable}\n")

    if args.status:
        problems = verify(root)
        print("\n" + "=" * 62)
        print("Looks healthy." if not problems else f"{problems} problem(s) above.")
        return 1 if problems else 0

    if args.live or args.pause:
        configure_env(root, force={"EMAIL_OUTBOX_WORKER": "true" if args.live else "false"})
        print("\n" + "=" * 62)
        print(f"Set to {'LIVE' if args.live else 'QUEUE-ONLY'}. "
              f"Restart the backend for it to take effect.")
        return 0

    if args.send:
        return send_test(root, args.send)

    write_files(root)
    configure_env(root)
    migrated = run_migration(root)
    problems = verify(root) if migrated else 1

    print("\n" + "=" * 62)
    if migrated and not problems:
        print("READY. Installed, configured and migrated.\n")
        print("Nothing sends yet - EMAIL_OUTBOX_WORKER=false.\n")
        print("Test it:")
        print("  1. restart the backend            start_app.bat")
        print("  2. python karnex_email_setup.py --send pavan.sanap@karnex.in")
        print("  3. submit a timesheet in the UI")
        print("  4. cd backend && python scripts\\test_email_notifications.py --outbox")
        print("  5. ... --drain                    release the queued mail")
        print("\nWhen you are satisfied:")
        print("  python karnex_email_setup.py --live      then restart the backend")
        return 0
    print("NOT FINISHED - see the [FAIL] lines above.")
    print("Paste this whole output back to Claude.")
    return 1


