def send_test(root: str, address: str) -> int:
    print(f"\n=== Real end-to-end test -> {address} ===")
    _load_backend(root)
    from datetime import datetime, timezone

    import sqlalchemy as sa

    from crm_db import get_session_factory
    from models import EmailOutbox
    from services.email_outbox import drain_once, queue_email, render_html, render_text

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")
    rows = [("Sent at", stamp), ("Purpose", "verifying the notification pipeline")]

    class Actor:
        full_name = "Karnex Test"
        email = (os.getenv("SMTP_USER") or "").strip()
        username = "test"

    with get_session_factory()() as db:
        row = queue_email(
            db, to_email=address, to_name="Test recipient",
            subject=f"Karnex notification test - {stamp}",
            body_text=render_text("Karnex notification test",
                                  "If you can read this, the outbox pipeline works.", rows=rows),
            body_html=render_html("Karnex notification test",
                                  "If you can read this, the outbox pipeline works.", rows=rows),
            event="test.notification", actor=Actor())
        if row is None:
            print(f"{BAD} nothing queued - address unusable, or notifications are disabled")
            return 1
        db.commit()
        row_id = row.id
        print(f"{OK} queued outbox row #{row_id}")

    print("  delivering...")
    print(f"  {drain_once(limit=5)}")

    with get_session_factory()() as db:
        row = db.get(EmailOutbox, row_id)
        status = row.status.value if hasattr(row.status, "value") else str(row.status)
        if status == "Sent":
            sender = os.getenv("SMTP_FROM") or os.getenv("SMTP_USER")
            print(f"\n{OK} SENT. Check {address}.")
            print(f'         From:     "{row.from_name}" <{sender}>')
            print(f"         Reply-To: {row.reply_to_email}")
            print("       Hit reply in your mail client - it should address the Reply-To,")
            print("       not the shared sender. That is the whole point of the design.")
            db.execute(sa.text("DELETE FROM email_outbox WHERE event = 'test.notification'"))
            db.commit()
            print(f"{OK} test rows cleaned up")
            return 0
        print(f"\n{BAD} status={status} after {row.attempts} attempt(s)")
        print(f"       {row.last_error}")
        print("\n       Most likely causes, in order:")
        print("         1. SMTP AUTH disabled for the mailbox (Microsoft 365 default)")
        print("         2. MFA on the account without an App Password")
        print("         3. The password in .env is stale")
        return 1


