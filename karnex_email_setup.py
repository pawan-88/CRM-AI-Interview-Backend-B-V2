def write_files(root: str) -> None:
    print("=== 1. Backend files ===")
    changed = 0
    for rel, b64 in FILES.items():
        dest = os.path.join(root, rel.replace("/", os.sep))
        data = base64.b64decode(b64)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        old = io.open(dest, "rb").read() if os.path.exists(dest) else None
        if old == data:
            continue
        io.open(dest, "wb").write(data)
        print(f"  {'updated' if old else 'created'}    {rel}")
        changed += 1
    print(f"{OK} {changed} file(s) written, {len(FILES) - changed} already current")


# -------------------------------------------------------------------- step 2

def _read_env(path: str) -> list[str]:
    if not os.path.exists(path):
        return []
    return io.open(path, encoding="utf-8", errors="replace").read().splitlines()


def _env_value(lines: list[str], key: str) -> str | None:
    """First occurrence wins - the app's loader uses setdefault, so a later
    duplicate of the same key is dead weight and never takes effect."""
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("#") or "=" not in stripped:
            continue
        if stripped.split("=", 1)[0].strip() == key:
            return stripped.split("=", 1)[1].strip()
    return None


_SECTION_HEADER = "# --- Notification email (added by karnex_email_setup.py) ---"


def _set_env(lines: list[str], key: str, value: str) -> list[str]:
    """Update the FIRST occurrence in place, or append under one tidy section.

    First occurrence matters: the app's .env loader uses setdefault, so a later
    duplicate of the same key is silently ignored. Editing in place is the only
    way a change actually takes effect.
    """
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("#") or "=" not in stripped:
            continue
        if stripped.split("=", 1)[0].strip() == key:
            lines[i] = f"{key}={value}"
            return lines
    if _SECTION_HEADER not in lines:
        if lines and lines[-1].strip():
            lines.append("")
        lines.append(_SECTION_HEADER)
    lines.append(f"{key}={value}")
    return lines


def configure_env(root: str, force: dict | None = None) -> None:
    print("\n=== 2. Configuration (.env) ===")
    path = os.path.join(root, ".env")
    if not os.path.exists(path):
        print(f"{BAD} no .env at {path}")
        return
    lines = _read_env(path)
    original = list(lines)

    # Required SMTP settings must already exist - never invent these.
    for key in ("SMTP_ENABLED", "SMTP_HOST", "SMTP_USER", "SMTP_PASSWORD"):
        val = _env_value(lines, key)
        shown = "(set)" if key == "SMTP_PASSWORD" and val else (val or "(missing)")
        print(f"{OK if val else BAD} {key:<28} {shown}")

    added = []
    for key, default, _why in ENV_DEFAULTS:
        if _env_value(lines, key) is None:
            lines = _set_env(lines, key, default)
            added.append(f"{key}={default}")
    for key, value in (force or {}).items():
        if _env_value(lines, key) != value:
            lines = _set_env(lines, key, value)
            added.append(f"{key}={value}  (changed)")

    for key, _d, _w in ENV_DEFAULTS:
        print(f"{INFO} {key:<28} {_env_value(lines, key)}")

    if lines != original:
        io.open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
        for entry in added:
            print(f"{OK} set {entry}")
    else:
        print(f"{OK} nothing to change")

    base = (_env_value(lines, "PUBLIC_BASE_URL") or "").strip()
    if not base or base.lower() == "auto":
        print(f"{WARN} PUBLIC_BASE_URL unset - emails will carry no link back to the app")
    elif any(p in base for p in ("192.168.", "10.", "127.0.0.1", "localhost", "172.16.")):
        print(f"{WARN} PUBLIC_BASE_URL = {base}")
        print("         That is a LAN address. Links inside emails will be dead for")
        print("         anyone off the office network. Not blocking - fix before go-live.")
    else:
        print(f"{OK} PUBLIC_BASE_URL = {base}")


